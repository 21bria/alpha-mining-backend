INSERT INTO kawi.mining_productions (
    created_at,
    updated_at,
    code,
    is_deleted,
    deleted_at,
    id,
    date_production,
    vendors,
    shift,
    loader,
    hauler,
    hauler_class,
    sources_area,
    loading_point,
    dumping_point,
    dome_id,
    distance,
    category_mine,
    time_dumping,
    time_loading,
    left_loading,
    block_id,
    from_rl,
    to_rl,
    id_material,
    bucket,
    ritase,
    bcm,
    tonnage,
    remarks,
    hauler_type,
    ref_materials,
    no_production,
    task_id,
    direct,
    iup_id,
    user_id
)
SELECT
    COALESCE(s.created_at, now()),
    COALESCE(s.updated_at, now()),
    -- 🔥 CODE BARU (UNIQUE)
    'MP-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || ROW_NUMBER() OVER (),
    false,
    NULL,
    -- UUID BARU
    gen_random_uuid(),
    s.date_production,
    s.vendors,
    s.shift,
    s.loader,
    s.hauler,
    s.hauler_class,
    s.sources_area,
    s.loading_point,
    s.dumping_point,
    s.dome_id,
    s.distance,
    s.category_mine,
    s.time_dumping,
    s.time_loading,
    s.left_loading,
    s.block_id,
    s.from_rl,
    s.to_rl,
    s.id_material,
    COALESCE(s.bucket, 0),
    COALESCE(s.ritase, 0),
    COALESCE(s.bcm, 0),
    COALESCE(s.tonnage, 0),
    s.remarks,
    s.hauler_type,
    s.ref_materials,
    s.no_production,
    NULL AS task_id,
    s.direct,
    -- IUP FIX
    1 AS iup_id,
    COALESCE(s.id_user, 1) AS user_id
FROM ext_kqms.productions_mines s;