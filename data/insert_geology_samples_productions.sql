INSERT INTO kawi.geology_samples_productions (
    created_at,
    updated_at,
    code,
    is_deleted,
    deleted_at,
    id,
    tgl_sample,
    shift,
    id_type_sample,
    id_method,
    id_material,
    sampling_area,
    sampling_point,
    from_rl,
    to_rl,
    batch_code,
    increments,
    fraction,
    "size",
    sample_weight,
    sample_number,
    remark,
    primer_raw,
    duplicate_raw,
    to_its,
    unit_truck,
    kode_batch,
    selling_pulp,
    sale_monitoring,
    sampling_deskripsi,
    "type",
    usage_status,
    pile_original,
    no_sample,
    sample_dup,
    discharge_area,
    product_code,
    gc_expect,
    iup_id,
    user_id
)
SELECT
    COALESCE(s.created_at, now()),
    COALESCE(s.updated_at, now()),
    'IUP-001-' || TO_CHAR(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || ROW_NUMBER() OVER (),
    false,
    NULL,
    gen_random_uuid(),
    s.tgl_sample,
    s.shift,
    NULLIF(s.id_type_sample::text, '')::bigint,
    NULLIF(s.id_method::text, '')::bigint,
    NULLIF(s.id_material::text, '')::bigint,
    s.sampling_area,
    s.sampling_point,
    s.from_rl,
    s.to_rl,
    s.batch_code,
    COALESCE(s.increments, 0),
    --  FIX
    s.fraction,
    s."size",
    COALESCE(s.sample_weight, 0),
    s.sample_number,
    s.remark,
    s.primer_raw,
    s.duplicate_raw,
    s.to_its,
    s.unit_truck,
    s.kode_batch,
    s.selling_pulp,
    s.sale_monitoring,
    s.sampling_deskripsi,
    s."type",
    s.usage_status,
    s.pile_original,
    s.no_sample,
    s.sample_dup,
    s.discharge_area,
    s.product_code,
    -- FIX gc_expect
    CASE
        WHEN s.gc_expect ~ '^[0-9]+(\.[0-9]+)?$'
        THEN s.gc_expect::numeric
        ELSE 0
    END,
    1,
    1
FROM ext_kqms.samples_productions s;
