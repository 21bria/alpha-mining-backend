INSERT INTO kawi.geology_ore_productions (
    created_at,
    updated_at,
    code,
    is_deleted,
    deleted_at,
    id,
    tgl_production,
    shift,
    id_prospect_area,
    id_block,
    from_rl,
    to_rl,
    id_material,
    grade_expect,
    grade_control,
    unit_truck,
    id_stockpile,
    id_pile,
    batch_code,
    "increment",
    batch_status,
    ritase,
    tonnage,
    pile_status,
    kode_batch,
    pile_original,
    stockpile_ori,
    truck_factor,
    ore_class,
    batch_status_set,
    dome_compositing,
    stock_compositing,
    status_dome,
    sale_adjust,
    remarks,
    category,
    direct,
    no_production,
    iup_id,
    user_id
)
SELECT
    COALESCE(s.created_at, now()),
    COALESCE(s.updated_at, now()),
    'IUP-001-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || ROW_NUMBER() OVER (),
    false,
    NULL,
    gen_random_uuid(),
    s.tgl_production,
    s.shift,
    s.id_prospect_area,
    s.id_block,
    s.from_rl,
    s.to_rl,
    s.id_material,
    COALESCE(s.grade_expect, 0),
    s.grade_control,
    s.unit_truck,
    s.id_stockpile,
    s.id_pile,
    s.batch_code,
    COALESCE(s."increment", 0),
    s.batch_status,
    COALESCE(s.ritase, 0),
    COALESCE(s.tonnage, 0),
    s.pile_status,
    s.kode_batch,
    s.pile_original,
    s.stockpile_ori,
    s.truck_factor,
    s.ore_class,
    s.batch_status_set,
    s.dome_compositing,
    s.stock_compositing,
    s.status_dome,
    s.sale_adjust,
    s.remarks,
    s.category,
    s.direct,
    s.no_production,
   1 AS iup_id,
   1 AS user_id
FROM ext_kqms.ore_productions s;